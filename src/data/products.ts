export function getProductBySlug(slug: string): FurnitureProduct | undefined {
  return allProducts.find((p) => p.slug === slug);
}

export function getProductsByRoom(room: RoomGroup): FurnitureProduct[] {
  return allProducts.filter((p) => p.room === room);
}

export function getProductsByCategory(category: CategorySlug): FurnitureProduct[] {
  if (category === "beds") {
    return allProducts.filter((p) => p.category === "beds");
  }
  return allProducts.filter((p) => p.category === category);
}

export function getRelatedProducts(
  product: FurnitureProduct,
  limit = 4
): FurnitureProduct[] {
  const sameCategory = allProducts.filter(
    (p) => p.id !== product.id && p.category === product.category
  );
  const sameRoom = allProducts.filter(
    (p) =>
      p.id !== product.id &&
      p.category !== product.category &&
      p.room === product.room
  );
  return [...sameCategory, ...sameRoom].slice(0, limit);
}
